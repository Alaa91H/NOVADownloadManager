export type OverlayMessageKey = keyof typeof overlayTranslations.en;
type OverlayLocale = keyof typeof overlayTranslations;

function normalizeOverlayLocale(rawLanguage?: string | null): OverlayLocale {
  const normalized = rawLanguage?.trim().replace('_', '-').toLowerCase();
  if (normalized && normalized in overlayTranslations) return normalized as OverlayLocale;
  const primary = normalized?.split('-', 1)[0];
  if (primary && primary in overlayTranslations) return primary as OverlayLocale;
  return 'en';
}

function browserUiLanguage(): string | undefined {
  try {
    return browser.i18n?.getUILanguage?.() || navigator.languages?.[0] || navigator.language;
  } catch {
    return navigator.languages?.[0] || navigator.language;
  }
}

export function translateOverlay(key: OverlayMessageKey, replacements?: Record<string, string | number>): string {
  let value: string = overlayTranslations[normalizeOverlayLocale(browserUiLanguage())][key] ?? overlayTranslations.en[key];
  if (!replacements) return value;
  for (const [name, replacement] of Object.entries(replacements)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}
